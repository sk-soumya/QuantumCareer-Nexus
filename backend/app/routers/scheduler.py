from datetime import datetime

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.core.dependencies import get_current_user
from app.database import get_db
from app.models.schedule import Schedule
from app.models.selection_round import SelectionRound
from app.models.user import User
from app.services.notification_service import create_notification
from app.services.scheduler import find_available_assignment


router = APIRouter(
    prefix="/scheduler",
    tags=["Automatic Scheduler"],
)


# ============================================================
# AUTOMATIC SCHEDULE GENERATION
# ============================================================

@router.post(
    "/generate/{round_id}",
)
def generate_schedule(
    round_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    # --------------------------------------------------------
    # Permission check
    # --------------------------------------------------------

    if current_user.role not in {
        "PLACEMENT_OFFICER",
        "ADMIN",
    }:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=(
                "Only placement officers and admins "
                "can generate schedules"
            ),
        )

    # --------------------------------------------------------
    # Get selection round
    # --------------------------------------------------------

    selection_round = db.get(
        SelectionRound,
        round_id,
    )

    if not selection_round:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Selection round not found",
        )

    # --------------------------------------------------------
    # Prevent duplicate schedule
    # --------------------------------------------------------

    existing_schedule = (
        db.query(Schedule)
        .filter(
            Schedule.selection_round_id == round_id
        )
        .first()
    )

    if existing_schedule:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="This selection round is already scheduled",
        )

    # --------------------------------------------------------
    # Find available assignment
    # --------------------------------------------------------

    assignment = find_available_assignment(
        db,
        selection_round,
    )

    if not assignment:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=(
                "No conflict-free combination of "
                "student, interviewer, room and time slot "
                "is currently available"
            ),
        )

    # --------------------------------------------------------
    # Create schedule
    # --------------------------------------------------------

    schedule = Schedule(
        selection_round_id=selection_round.id,
        student_id=assignment["student_id"],
        interviewer_id=assignment["interviewer_id"],
        room_id=assignment["room_id"],
        time_slot_id=assignment["time_slot_id"],
        status="SCHEDULED",
        notes="Automatically generated by CAMPUSLINK",
    )

    db.add(schedule)

    # --------------------------------------------------------
    # Update selection round
    # --------------------------------------------------------

    selection_round.status = "SCHEDULED"
    selection_round.scheduled_at = datetime.utcnow()

    # --------------------------------------------------------
    # Create student notification
    # --------------------------------------------------------

    create_notification(
        db=db,
        user_id=assignment["student_id"],
        title="Interview Scheduled",
        message=(
            "Your interview has been scheduled successfully. "
            "Please check your schedule details."
        ),
        notification_type="SCHEDULE",
    )

    # --------------------------------------------------------
    # Save schedule + round + notification together
    # --------------------------------------------------------

    db.commit()
    db.refresh(schedule)

    # --------------------------------------------------------
    # Response
    # --------------------------------------------------------

    return {
        "message": "Schedule generated successfully",
        "schedule_id": schedule.id,
        "selection_round_id": schedule.selection_round_id,
        "student_id": schedule.student_id,
        "interviewer_id": schedule.interviewer_id,
        "room_id": schedule.room_id,
        "time_slot_id": schedule.time_slot_id,
        "status": schedule.status,
    }